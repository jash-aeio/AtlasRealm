// SessionStart: prints a short orientation (branch, milestone, next task, uncommitted changes).
// Stdout from a SessionStart hook is added to Claude's context.
import fs from 'node:fs';
import path from 'node:path';
import { readInput, git } from './lib.mjs';

const input = await readInput();
const root = process.env.CLAUDE_PROJECT_DIR || input?.cwd || process.cwd();

const branch = git('rev-parse --abbrev-ref HEAD', root) ?? '(no commits yet)';
const dirty = (git('status --porcelain', root) ?? '').split('\n').filter(Boolean).length;

function section(md, heading) {
  const re = new RegExp(`^## ${heading}\\s*\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, 'm');
  return (md.match(re)?.[1] ?? '').trim().split('\n').slice(0, 6).join('\n');
}

let milestone = '(status file missing)';
let next = '';
try {
  const md = fs.readFileSync(path.join(root, 'docs/status/IMPLEMENTATION_STATUS.md'), 'utf8');
  milestone = section(md, 'Current milestone');
  next = section(md, 'Next task');
} catch {
  // Missing or unreadable status file: keep the defaults above.
}

const lines = [
  '## Atlas Realm session context (auto-generated by .claude/hooks/session-context.mjs)',
  `- Branch: ${branch}${['main', 'master'].includes(branch) ? '  ⚠ on main. Create a feature branch before editing code (/start-task).' : ''}`,
  `- Uncommitted changes: ${dirty} file(s)`,
  `- Current milestone: ${milestone}`,
  next ? `- Next task:\n${next}` : '',
  '- Follow the session loop in CLAUDE.md. Verify status claims against the code before relying on them.',
];
process.stdout.write(lines.filter(Boolean).join('\n') + '\n');
process.exit(0);
